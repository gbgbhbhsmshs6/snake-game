/*==============================================================
 *  step1_board.c  ——  第 1 步：把"棋盘"画出来
 *--------------------------------------------------------------
 *  这一步只做三件事：
 *    1. 用二维数组表示一个 20x20 的棋盘
 *    2. 用 for 循环在棋盘边缘画 '#'
 *    3. 用 rand() 随机放一颗食物 '*'
 *
 *  编译： gcc step1_board.c -o step1
 *  运行： step1
 *
 *  学完这一节你就掌握了"字符游戏"的本质：
 *    游戏画面 = 一个二维 char 数组，改数组就是改画面。
 *==============================================================*/

#include <stdio.h>
#include <stdlib.h>
#include <time.h>

/* #define 叫"宏定义"，相当于给数字起个名字。
 * 好处：以后想把棋盘改成 30x30，只改这一行就够了。
 * 约定：宏名用全大写，这是 C 语言的习惯。            */
#define WIDTH  20   /* 棋盘的宽（列数） */
#define HEIGHT 20   /* 棋盘的高（行数） */

int main(void)
{
    /* ---------- 1. 准备棋盘 ----------
     * char screen[行数][列数] 就是一个二维数组。
     * 为什么是 HEIGHT+2 和 WIDTH+3？
     *   +2 是因为棋盘外面还要一圈边框 '#'，上下左右各多一行/列；
     *   +3 里的额外 1 是留给字符串结尾的 '\0'，这样后面
     *   就可以用 printf("%s") 整行输出，比一个一个 putchar 省事。 */
    char screen[HEIGHT + 2][WIDTH + 3];

    int x, y;                 /* x = 列号(左右)，y = 行号(上下) */

    /* ---------- 2. 先全部填成空格 ----------
     * 注意：局部数组里一开始是"垃圾值"，必须自己初始化。 */
    for (y = 0; y < HEIGHT + 2; y++) {
        for (x = 0; x < WIDTH + 2; x++) {
            screen[y][x] = ' ';
        }
        screen[y][WIDTH + 2] = '\0';   /* 每行末尾放上字符串结束符 */
    }

    /* ---------- 3. 画边框 ----------
     * 只要满足"最上/最下/最左/最右"这四个条件之一，就是边框。 */
    for (y = 0; y < HEIGHT + 2; y++) {
        for (x = 0; x < WIDTH + 2; x++) {
            int is_border = (y == 0 || y == HEIGHT + 1 ||
                             x == 0 || x == WIDTH + 1);
            if (is_border) {
                screen[y][x] = '#';
            }
        }
    }

    /* ---------- 4. 随机放一颗食物 ----------
     * srand() 设置"随机种子"。
     * 如果只写 rand() 不写 srand()，每次运行得到的数字完全一样。
     * time(NULL) 返回从 1970 年到现在经过的秒数，每次运行都不同，
     * 所以拿它当种子，就能得到"真随机"的效果。
     * 注意：srand() 在整个程序里只调用一次，不要放在循环里！ */
    srand((unsigned)time(NULL));

    int food_x = rand() % WIDTH;    /* % WIDTH 把结果限制在 0 ~ WIDTH-1 */
    int food_y = rand() % HEIGHT;

    /* 食物在"游戏坐标"里是 (food_x, food_y)，
     * 但屏幕上要整体右下移一格给它让出边框的位置，所以 +1。 */
    screen[food_y + 1][food_x + 1] = '*';

    /* ---------- 5. 把数组打印到屏幕上 ---------- */
    for (y = 0; y < HEIGHT + 2; y++) {
        printf("%s\n", screen[y]);
    }

    printf("\n食物的游戏坐标是 (%d, %d)\n", food_x, food_y);
    printf("多运行几次，看看食物位置是不是每次都变？\n");

    return 0;   /* 返回 0 表示程序正常结束 */
}
